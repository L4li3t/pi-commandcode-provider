/**
 * Structural types shared by the catalog pipeline.
 *
 * These are intentionally dependency-free (no runtime or type imports from
 * Pi packages) so the merge logic can be unit-tested with plain Node and the
 * sync script can regenerate the snapshot without loading Pi.
 */

/** Pi chat API identifiers used by this provider. */
export type ChatApiId = "openai-completions" | "openai-responses" | "anthropic-messages";

/** Wire endpoints exposed by the Command Code Provider API. */
export type Endpoint = "/chat/completions" | "/responses" | "/messages";

export interface CatalogCost {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
	/** Request-wide input pricing tiers, passed through to Pi when present. */
	tiers?: readonly unknown[];
}

export interface CatalogPromptCache {
	short?: number;
	long?: number;
}

export type CatalogThinkingLevelMap = Partial<Record<string, string | null>>;

/**
 * One bundled catalog entry (generated by scripts/sync-catalog.mjs).
 * Every field is optional: absent fields fall back to family heuristics.
 */
export interface CatalogEntry {
	id: string;
	name?: string;
	contextWindow?: number;
	endpoints?: string[];
	/** Explicit protocol override; otherwise derived from endpoints. */
	api?: ChatApiId;
	maxTokens?: number;
	input?: Array<"text" | "image">;
	reasoning?: boolean;
	thinkingLevelMap?: CatalogThinkingLevelMap;
	promptCache?: CatalogPromptCache;
	cost?: CatalogCost;
	compat?: Record<string, unknown>;
	/** Hide a model from the picker (known-broken or deliberately parked). */
	hidden?: boolean;
	/** Provenance for audits: "pi-ai", "models.dev", "override", "fact", "default". */
	source?: string;
}

/** Raw model object returned by GET {baseUrl}/models. */
export interface RemoteModel {
	id: string;
	name?: string;
	context_length?: number;
	supported_endpoints?: string[];
	created?: number;
	owned_by?: string;
}

/** Remote + bundled metadata resolved into one usable model description. */
export interface MergedModel {
	id: string;
	name: string;
	api: ChatApiId;
	contextWindow: number;
	maxTokens: number;
	input: Array<"text" | "image">;
	reasoning: boolean;
	thinkingLevelMap?: CatalogThinkingLevelMap;
	promptCache?: CatalogPromptCache;
	cost: CatalogCost;
	compat?: Record<string, unknown>;
	endpoints: string[];
	created?: number;
	hidden?: boolean;
	/** The raw live entry, retained so persisted catalogs can be re-merged. */
	remote?: RemoteModel;
	/** Which layer supplied the non-live metadata. */
	source: "catalog" | "family" | "override";
}

/**
 * Facts probed per model and persisted alongside the snapshot. The sync
 * script writes these; the runtime merge ignores them (they are already
 * folded into the generated catalog).
 */
export interface CatalogFacts {
	vision?: boolean;
	reasoning?: boolean;
	contextWindow?: number;
	observedAt?: string;
}
